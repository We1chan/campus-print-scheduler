"""Compare three production policies with a fixed, independently audited score."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

POLICIES = ('fcfs', 'sjf', 'balanced')
SEEDS = (20261010, 20261011, 20261012)
CUSTOMERS = (150, 300, 600, 900)
REFERENCE_MS = 1800000


def require(condition, message):
    if not condition:
        raise ValueError(message)


def nominal_cost(job, printer=None):
    multiplier = 2 if job['paper'] == 'a3' else 1
    faces = job['pages'] * job['copies']
    sheets = ((job['pages']+1)//2 if job['duplex'] else job['pages']) * job['copies']
    toner = 45 if job['color'] else 7 if printer and printer['color'] else 5
    return multiplier * (3*sheets + toner*faces)


def audit_run(report, run):
    """Rebuild waits, fulfillment, cost and quality from actual dispatches."""
    horizon = report['horizon_ms']
    jobs = {j['job_id']: j for j in run['jobs']}
    require(len(jobs) == run['accepted'], 'duplicate or missing accepted orders')
    starts, completed, actual_cost = {}, {}, {}
    available = [0] * len(report['fleet'])
    for d in run['dispatches']:
        ident = d['job_id']
        require(ident in jobs and ident not in starts, 'unknown or duplicate dispatch')
        j = jobs[ident]
        index = d['printer']
        require(isinstance(index, int) and 0 <= index < len(available), 'invalid printer')
        p = report['fleet'][index]
        require(p['online'] and (j['paper'] != 'a3' or p['a3']) and
                (not j['color'] or p['color']) and (not j['duplex'] or p['duplex']), 'incompatible device')
        require(max(j['submitted_ms'], available[index]) <= d['started_ms'] < horizon, 'arrival or overlap violation')
        expected = j['pages'] * j['copies'] * (p['color_page_ms'] if j['color'] else p['mono_page_ms'])
        expected *= 2 if j['paper'] == 'a3' else 1
        require(d['finished_ms']-d['started_ms'] == expected, 'wrong processing duration')
        starts[ident] = d['started_ms']
        actual_cost[ident] = nominal_cost(j, p)
        available[index] = d['finished_ms']
        require(j['first_started_ms'] == d['started_ms'] and j['cost_cents'] == actual_cost[ident], 'snapshot differs from dispatch')
        if d['finished_ms'] <= horizon:
            completed[ident] = d['finished_ms']
            require(j['state'] == 'completed' and j['finished_ms'] == d['finished_ms'], 'completion differs from trace')
        else:
            require(j['state'] == 'running' and j['finished_ms'] is None, 'unfinished work must not settle')
    require(all(j['state'] == 'queued' and j['first_started_ms'] is None for ident, j in jobs.items() if ident not in starts),
            'unstarted orders must remain queued')
    waits = sorted(starts.get(ident, horizon)-j['submitted_ms'] for ident, j in jobs.items())
    mean = sum(waits)/len(waits) if waits else 0
    p95 = waits[(len(waits)*95+99)//100-1] if waits else 0
    express = [ident for ident, j in jobs.items() if j['service'] == 'express']
    timely = sum(ident in completed and 0 < completed[ident] <= jobs[ident]['deadline_ms'] for ident in express)
    # Zero-duration completions are not generated by this replay, but have the
    # same deadline semantics as the production metric.
    timely += sum(ident in completed and completed[ident] == 0 and jobs[ident]['deadline_ms'] > 0 for ident in express)
    potential = sum(max(0, j['quoted_cents']-nominal_cost(j)) for j in jobs.values())
    profit = sum(jobs[ident]['quoted_cents']-jobs[ident]['refund_cents']-actual_cost[ident] for ident in completed)
    revenue = sum(jobs[ident]['quoted_cents']-jobs[ident]['refund_cents'] for ident in completed)
    w = 0.5/(1+mean/REFERENCE_MS) + 0.5/(1+p95/REFERENCE_MS) if waits else 0
    e = timely/len(express) if express else (1 if waits else 0)
    c = min(1, max(0, profit/potential)) if potential else 0
    score = 100*(w+e+c)/3 if waits else 0
    metrics = {'average_observed_wait_ms': mean, 'p95_observed_wait_ms': p95,
               'express_accepted': len(express), 'express_on_time': timely, 'express_on_time_rate': e,
               'potential_contribution_cents': potential, 'waiting_score': w, 'contribution_score': c,
               'quality_score': score, 'contribution_cents': profit, 'revenue_cents': revenue, 'completed': len(completed)}
    for key, expected in metrics.items():
        require(math.isclose(run[key], expected, rel_tol=1e-10, abs_tol=1e-8), f'{key} differs from independently audited trace')
    return metrics


def audit_report(report):
    require(len(report['runs']) == 21, 'expected seven matched cohorts and three policies')
    require(report['evaluation']['name'] == 'balanced-shop-quality-v1' and
            report['evaluation']['wait_reference_ms'] == REFERENCE_MS and
            all(report['evaluation'][k] == 1 for k in ('waiting_weight', 'express_weight', 'contribution_weight')),
            'evaluation weights must remain fixed')
    inputs, groups, rows = {}, {}, []
    fields = ('job_id', 'pages', 'copies', 'submitted_ms', 'paper', 'color', 'duplex', 'service', 'quoted_cents', 'deadline_ms')
    for run in report['runs']:
        key = (run['mode'], run['budget_sensitive_percent'], run['discounts'])
        cohort = [tuple(j[f] for f in fields) for j in run['jobs']]
        if key in inputs:
            require(inputs[key] == cohort, 'policy comparisons changed accepted orders, quotes or promises')
        inputs[key] = cohort
        policy = run['policy']
        require(policy in POLICIES and policy not in groups.setdefault(key, {}), 'unexpected or duplicate policy')
        metrics = audit_run(report, run)
        groups[key][policy] = metrics['quality_score']
        rows.append({'mode': key[0], 'budget_sensitive_percent': key[1], 'discounts': key[2], 'policy': policy, **metrics})
    require(len(groups) == 7 and all(set(g) == set(POLICIES) for g in groups.values()), 'unmatched policy cohorts')
    return rows


def run_benchmark(experiment, output, seeds=SEEDS, customers=CUSTOMERS, hours=8):
    experiment, output = Path(experiment).resolve(), Path(output).resolve()
    require(not output.exists(), 'benchmark output must be a new directory')
    output.mkdir(parents=True)
    rows, files, commands = [], {}, []
    for seed in seeds:
        for count in customers:
            path = output / f'seed-{seed}-customers-{count}.json'
            command = [str(experiment), '--seed', str(seed), '--customers', str(count), '--hours', str(hours), '--output', str(path)]
            subprocess.run(command, check=True, capture_output=True, timeout=45)
            report = json.loads(path.read_text(encoding='utf-8'))
            rows.extend({'seed': seed, 'customers': count, **row} for row in audit_report(report))
            files[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
            commands.append(command)
    means = {p: sum(r['quality_score'] for r in rows if r['policy'] == p)/sum(r['policy'] == p for r in rows) for p in POLICIES}
    groups = {}
    for row in rows:
        key = (row['seed'], row['customers'], row['mode'], row['budget_sensitive_percent'], row['discounts'])
        groups.setdefault(key, {})[row['policy']] = row['quality_score']
    wins = {p: sum(g['balanced'] > g[p]+1e-9 for g in groups.values()) for p in POLICIES[:2]}
    losses = {p: sum(g['balanced'] < g[p]-1e-9 for g in groups.values()) for p in POLICIES[:2]}
    summary = {'evaluation': 'balanced-shop-quality-v1', 'seeds': list(seeds), 'customers': list(customers), 'hours': hours,
               'matched_cohorts': len(groups), 'policy_means': means, 'balanced_wins': wins, 'balanced_losses': losses,
               'passed': means['balanced'] > max(means['fcfs'], means['sjf']), 'rows': rows,
               'evidence': {'experiment_sha256': hashlib.sha256(experiment.read_bytes()).hexdigest(),
                            'audit_script_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                            'reports_sha256': files, 'commands': commands}}
    (output/'summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--experiment', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    summary = run_benchmark(args.experiment, args.output)
    print(json.dumps({k:v for k,v in summary.items() if k not in ('rows', 'evidence')}, indent=2))
    return 0 if summary['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
